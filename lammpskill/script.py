"""Input scripts from a Python spec (rendered in the order the manual's "Commands_structure" page prescribes:
initialization, system definition, settings, run), presets for the chapter systems, and a checker for the mistakes
the manual warns about (each finding names its manual page). No script here is copied from LAMMPS."""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field

import numpy as np

from . import __version__
from .io.box import Box
from .io.data import DataFile


@dataclass
class Stage:
    kind: str
    args: str


@dataclass
class Spec:
    units: str = "lj"
    dimension: int = 3
    atom_style: str = "atomic"
    boundary: str = "p p p"
    lattice: str | None = None
    region: str | None = None
    create_box: int | None = None
    create_atoms: str | None = None
    read_data: str | None = None
    masses: dict = field(default_factory=dict)
    pair_style: str | None = None
    pair_coeffs: list = field(default_factory=list)
    bond_style: str | None = None
    bond_coeffs: list = field(default_factory=list)
    angle_style: str | None = None
    angle_coeffs: list = field(default_factory=list)
    dihedral_style: str | None = None
    dihedral_coeffs: list = field(default_factory=list)
    kspace_style: str | None = None
    special_bonds: str | None = None
    neighbor: str | None = None
    neigh_modify: str | None = None
    timestep: float | None = None
    groups: list = field(default_factory=list)
    velocity: list = field(default_factory=list)
    computes: list = field(default_factory=list)
    fixes: list = field(default_factory=list)
    dumps: list = field(default_factory=list)
    thermo: int = 100
    thermo_style: str = "custom step temp pe ke etotal press"
    thermo_modify: str | None = None
    stages: list = field(default_factory=lambda: [Stage("run", "100")])
    pre: list = field(default_factory=list)
    post: list = field(default_factory=list)
    write_data: str | None = None
    comment: str = ""


def render(spec: Spec) -> str:
    L = ["# generated by lammps-skill %s%s" % (__version__, (" — " + spec.comment) if spec.comment else ""), ""]
    L += spec.pre
    L += ["# --- initialization", "units %s" % spec.units, "dimension %d" % spec.dimension, "boundary %s" % spec.boundary,
          "atom_style %s" % spec.atom_style]
    L += ["", "# --- system definition"]
    if spec.lattice:
        L.append("lattice %s" % spec.lattice)
    if spec.region:
        L.append("region %s" % spec.region)
    if spec.create_box is not None:
        L.append("create_box %d %s" % (spec.create_box, (spec.region or "box").split()[0]))
    if spec.create_atoms:
        L.append("create_atoms %s" % spec.create_atoms)
    if spec.read_data:
        L.append("read_data %s" % spec.read_data)
    for t, m in sorted(spec.masses.items()):
        L.append("mass %d %.10g" % (t, m))
    L += ["", "# --- settings"]
    if spec.pair_style:
        L.append("pair_style %s" % spec.pair_style)
    L += ["pair_coeff %s" % c for c in spec.pair_coeffs]
    for name, style, coeffs in (("bond", spec.bond_style, spec.bond_coeffs), ("angle", spec.angle_style, spec.angle_coeffs),
                                ("dihedral", spec.dihedral_style, spec.dihedral_coeffs)):
        if style:
            L.append("%s_style %s" % (name, style))
            L += ["%s_coeff %s" % (name, c) for c in coeffs]
    if spec.kspace_style:
        L.append("kspace_style %s" % spec.kspace_style)
    if spec.special_bonds:
        L.append("special_bonds %s" % spec.special_bonds)
    if spec.neighbor:
        L.append("neighbor %s" % spec.neighbor)
    if spec.neigh_modify:
        L.append("neigh_modify %s" % spec.neigh_modify)
    if spec.timestep is not None:
        L.append("timestep %.10g" % spec.timestep)
    L += ["group %s" % g for g in spec.groups]
    L += ["velocity %s" % v for v in spec.velocity]
    L += ["compute %s" % c for c in spec.computes]
    L += ["fix %s" % f for f in spec.fixes]
    L += ["dump %s" % d for d in spec.dumps]
    L += ["thermo %d" % spec.thermo, "thermo_style %s" % spec.thermo_style]
    if spec.thermo_modify:
        L.append("thermo_modify %s" % spec.thermo_modify)
    L += ["", "# --- run"]
    for st in spec.stages:
        L.append("%s %s" % (st.kind, st.args))
    if spec.write_data:
        L.append("write_data %s" % spec.write_data)
    L += spec.post
    return "\n".join(L) + "\n"


