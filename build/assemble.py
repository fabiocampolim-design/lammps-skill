"""Assemble the chapter notebooks from the chapter modules in this directory.

Every chapter is self-contained: a generated header (title, contents with anchors, what it needs),
the shared Setup cell, the chapter module's cells, and a generated tally cell that asserts what the
chapter claimed. Outputs are not produced here -- run ``build/execute.py`` afterwards.

Chapters marked ``needs_lammps=False`` must run on a machine with no LAMMPS installed; a test
enforces that they never reach for the runner.

Usage:
    python build/assemble.py                  # every chapter into chapters/
    python build/assemble.py --which 00       # one chapter
    python build/assemble.py --outdir out/nb  # elsewhere
    python build/assemble.py --list           # show chapters and cell counts, write nothing
    python build/assemble.py --log-dir DIR    # audit record per invocation (default <outdir>/logs)
"""

import argparse
import datetime as dt
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, ROOT)

import nbbuild                                    # noqa: E402
from lammpskill import __version__                # noqa: E402

# key -> module name, slug, title, whether the chapter needs a LAMMPS installation.
_SPEC = [
    ("00", "chapter00_orientation", "Orientation", "Orientation: LAMMPS, the routes, and this toolkit", False),
    ("08", "chapter08_reading", "Reading_What_LAMMPS_Writes",
     "Reading What LAMMPS Writes: data, dump, log and restart formats, and four pitfalls", False),
    ("09", "chapter09_choosing_build", "Choosing_A_Build",
     "Choosing a Build: what the 314-case examples sweep says about package list vs package count", False),
]

CHAPTERS = {}
for _key, _mod, _slug, _title, _needs in _SPEC:
    CHAPTERS[_key] = {"module": importlib.import_module(_mod), "slug": _slug,
                      "title": _title, "needs_lammps": _needs}

SETUP = '''\
# Setup -- run me first.
import sys, os
sys.path.insert(0, os.path.abspath(".."))          # the product root, when run from chapters/

import lammpskill
from lammpskill.install import detect_all

print("lammps-skill", lammpskill.__version__, "| python", sys.version.split()[0])
INSTALLATIONS = detect_all()
if INSTALLATIONS:
    for i in INSTALLATIONS:
        print("  %-11s %-24s %s" % (i.route, i.version, i.executable or "(library only)"))
else:
    print("  no LAMMPS installation detected -- chapters marked 'no LAMMPS needed' still run;")
    print("  the others load their recorded results instead (record-or-run).")
'''


def header(key, ch):
    sections = [src.splitlines()[0][3:].strip()
                for kind, src in ch["module"].CELLS
                if kind == "md" and src.lstrip().startswith("## ")]
    lines = ["# Chapter %s — %s" % (key, ch["title"]), "",
             "*lammps-skill %s. Generated by `build/assemble.py` — do not edit this notebook; "
             "edit `build/%s.py` and re-assemble.*" % (__version__, ch["module"].__name__), "",
             "**Needs a LAMMPS installation:** %s" % ("yes" if ch["needs_lammps"] else
                                                      "no — this chapter runs anywhere"), "",
             "## Contents", ""]
    lines += ["%d. [%s](#%s)" % (n, s, nbbuild.anchor(s)) for n, s in enumerate(sections, 1)]
    return "\n".join(lines)


def tally(key, ch):
    checks = getattr(ch["module"], "TALLY", [])
    body = ["# Tally -- what this chapter claimed, checked.",
            "checks = []"]
    for expr, label in checks:
        body.append("checks.append((%r, bool(%s)))" % (label, expr))
    body += ["",
             "for label, ok in checks:",
             "    print(('PASS' if ok else 'FAIL'), label)",
             "assert all(ok for _, ok in checks), 'chapter %s: a claim above is not true'" % key,
             "print('chapter %s: %%d claim(s) checked' %% len(checks))" % key]
    return "\n".join(body)


def assemble_one(key, outdir):
    ch = CHAPTERS[key]
    os.makedirs(outdir, exist_ok=True)
    cells = [("md", header(key, ch)), ("code", SETUP)] + list(ch["module"].CELLS) + [("code", tally(key, ch))]
    path = os.path.join(outdir, "LAMMPS_%s_%s.ipynb" % (key, ch["slug"]))
    return nbbuild.write_notebook(cells, path)


def build_parser():
    ap = argparse.ArgumentParser(prog="assemble", description=__doc__.splitlines()[0])
    ap.add_argument("--which", default="all", help="chapter key (e.g. 00) or 'all'")
    ap.add_argument("--outdir", default=os.path.join(ROOT, "chapters"), help="where the notebooks go")
    ap.add_argument("--log-dir", default=None, help="audit log directory (default <outdir>/logs)")
    ap.add_argument("--list", action="store_true", help="show chapters and cell counts, write nothing")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--version", action="version", version="lammps-skill %s" % __version__)
    return ap


def main(argv=None):
    a = build_parser().parse_args(argv)
    if a.list:
        for key in sorted(CHAPTERS):
            ch = CHAPTERS[key]
            print("%s  %-28s %3d cells  %s" % (key, ch["slug"], len(ch["module"].CELLS),
                                               "needs LAMMPS" if ch["needs_lammps"] else "runs anywhere"))
        return 0
    keys = sorted(CHAPTERS) if a.which == "all" else [a.which]
    for key in keys:
        if key not in CHAPTERS:
            print("unknown chapter %r (try --list)" % key)
            return 2
        path = assemble_one(key, a.outdir)
        if a.verbose or True:
            print("%s -> %s (%d bytes)" % (key, path, os.path.getsize(path)))
    log_dir = a.log_dir or os.path.join(a.outdir, "logs")
    os.makedirs(log_dir, exist_ok=True)
    with open(os.path.join(log_dir, "assemble.log"), "a", encoding="utf-8", newline="\n") as f:
        f.write("%s lammps-skill %s assembled %s\n"
                % (dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%MZ"), __version__, ",".join(keys)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
